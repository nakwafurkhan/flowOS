import assert from 'node:assert/strict';
import {seed,USERS,SCALE,quantityBase,totals,saveQuote,sendQuote,convertQuote,recordPayment,outstanding,recommendation,updateTask,receiveStock,answer,scoped} from './model.mjs';
const [employee,manager,ceo]=USERS;
let db=seed();
assert.equal(quantityBase(db.products[0],'bag','0.5'),25*SCALE);
assert.equal(quantityBase(db.products[0],'lb','1'),453592);
assert.throws(()=>quantityBase(db.products[1],'kg','0.001'),/fraction/);
assert.throws(()=>quantityBase(db.products[0],'bag','-1'));
assert.equal(totals(db,[{productId:'P1',unit:'bag',qty:'50'}]).total,100625);
assert.equal(scoped(employee,db.customers[2]),false);
assert.equal(scoped(manager,db.customers[2]),true);
assert.equal(scoped(manager,db.customers[3]),false);
assert.equal(scoped(ceo,db.customers[3]),true);
assert(!answer(db,employee,'Eastern Works (demo) balance').text.includes('23000'));
assert.equal(answer(db,employee,'Al-Rimal balance').links.length,2);
assert.throws(()=>recordPayment(db,employee,'S1003',100,'TEST'),/Access/);
assert.throws(()=>updateTask(db,employee,'T2','approve'),/Access/);
updateTask(db,employee,'T1','submit',{outcome:'Customer promised payment.'});
updateTask(db,manager,'T1','return',{comment:'Add a date.'});
updateTask(db,employee,'T1','submit',{outcome:'Will pay on Monday.',promise:'2026-11-02'});
updateTask(db,manager,'T1','approve');assert.equal(db.tasks[0].status,'Approved');
const q=saveQuote(db,employee,{customerId:'C101',lines:[{productId:'P1',unit:'bag',qty:'50'},{productId:'P2',unit:'dozen',qty:'10',supplierId:'SUP1',supplierDue:'2026-11-07'}]});
assert.equal(q.total,104075);assert.equal(q.lines[1].short,96*SCALE);
assert.equal(db.payables.length,1);sendQuote(db,employee,q.id);
assert.throws(()=>convertQuote(db,employee,q.id,false),/fulfilment/);
const sale=convertQuote(db,employee,q.id,true);assert.equal(db.products[1].stock,0);
assert.throws(()=>convertQuote(db,employee,q.id,true));
recordPayment(db,employee,sale.id,50000,'DEMO-003');
assert.equal(outstanding(db,sale),54075);
const ap=db.payables.at(-1);assert.equal(ap.due,'2026-11-07');assert.equal(ap.paid,0);assert(recommendation(db,ap)>0);
assert.throws(()=>recordPayment(db,employee,sale.id,100,'DEMO-003'),/already/);
assert.throws(()=>recordPayment(db,employee,sale.id,999999,'DEMO-004'),/no more/);
assert.throws(()=>receiveStock(db,employee,'P1','1','tonne','R1',true),/managers/);
receiveStock(db,manager,'P1','1','tonne','R1',true);assert.equal(db.products[0].stock,6000*SCALE);
assert.throws(()=>receiveStock(db,manager,'P1','1','tonne','R1',true),/already/);
console.log('PASS: conversions, VAT, scoped access, task review, quote-to-sale, stock, partial payments and supplier due-date invariants.');
